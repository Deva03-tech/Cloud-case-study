"""Generate RESULTS.md: every number is read from results/ files (no retyping).

Sections: tables (calibration, sweep, validation, Redset, stats pointer), figures, result
file inventory, deviations and cuts (from DECISIONS.md, Dell takeover section), threats.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src import common  # noqa: E402

R = common.RESULTS_DIR
POL = ["P-peak", "P-mean", "P-sched", "S-default", "S-tuned", "S-floor", "S-prewarm"]


def j(name: str) -> dict | None:
    p = R / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def d_pass(v2: dict) -> bool:
    return bool(v2["data"]["sim"].get("v2", {}).get("accept", {}).get("overall", False))


def md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in r.tolist()) + " |")
    return "\n".join(lines)


def main() -> int:
    out = ["# RESULTS", "",
           "Generated by `scripts/make_results_md.py` from the files in `results/`; every number "
           "below is read from the named file. Host: Dell G15 (results/machine_dell.json). "
           "HP measurements in results/hp_bootstrap/ are not used.", ""]
    m = j("machine_dell")
    if m:
        d = m["data"]
        out += ["## Machine", "", f"{d['machine']}, {d['cpu']} ({d['cores']} cores / {d['threads']} threads), "
                f"{d['ram_gb']} GB RAM, Windows build {d['windows_build']}. Source: results/machine_dell.json.", ""]

    c = j("calib_docker")
    if c:
        rows = []
        for q in sorted(c["data"]["s1"]["queries"]):
            r = {"query": q}
            for s in ("s1", "s2", "s4"):
                qq = c["data"][s]["queries"][q]
                r[f"{s} warm med"] = qq["warm"]["median_s"]
                r[f"{s} warm p95"] = qq["warm"]["p95_s"]
                r[f"{s} cold med"] = qq["cold_first_query"]["median_s"]
            rows.append(r)
        sent = ", ".join(f"{s}: {c['data'][s]['sentinel_q6_start_s']}→{c['data'][s]['sentinel_q6_end_s']} s"
                         for s in ("s1", "s2", "s4"))
        out += ["## Table 1 – Docker calibration (seconds)", "",
                "Source: results/calib_docker.json. s1/s2/s4 = 1/2/4 vCPU with 2/3/5 GB; 3 cold runs, "
                "1 warm-up + 5 warm reps per query and size.", "", md_table(pd.DataFrame(rows)), "",
                f"Q6 sentinel start→end: {sent}.", ""]

    sw = j("sweep")
    if sw:
        df = pd.read_parquet(R / "sweep.parquet")
        df = df[~df.aux]
        g = df.groupby(["intensity", "gap", "policy"]).agg(
            p95=("p95_s", "mean"), p99=("p99_s", "mean"), cost1k=("cost_per_1k_usd", "mean"),
            vcpu_s=("compute_vcpu_s", "mean"), cold=("cold_starts", "mean"),
            meets_p95=("meets_p95", "mean")).round(4).reset_index()
        g["policy"] = pd.Categorical(g.policy, POL)
        g = g.sort_values(["intensity", "gap", "policy"])
        d = sw["data"]
        out += ["## Table 2 – Synthetic burst sweep (means over 10 seeds)", "",
                f"Source: results/sweep.parquet, results/sweep.json. {d['runs_total']} runs; "
                f"p95 target {d['p95_target_s']} s, p99 target {d['p99_target_s']} s; "
                "meets_p95 = share of seeds meeting the p95 target. Serverless priced as Aurora "
                "Serverless v2, provisioned as RDS (configs/prices.yaml).", "", md_table(g), "",
                "S-tuned timeout per cell: " + ", ".join(
                    f"{k} τ={v['tau_s']:.0f}s{'' if v['meets_target'] else ' (no τ met target)'}"
                    for k, v in d["tuned_tau"].items()) + ".", ""]

    v = j("validation")
    if v:
        d = v["data"]
        out += ["## Table 3 – Validation (simulator vs real Docker s2 replay, 10 min)", "",
                "Source: results/validation.json. Acceptance frozen before the run: |p95 error| ≤ 25 %, "
                "|compute-seconds error| ≤ 20 %.", "",
                "| metric | real | sim (mean of 10 seeds) | error | pass |", "|---|---|---|---|---|",
                f"| p95 latency (s) | {d['real']['p95_s']:.4f} | {d['sim']['p95_s_mean']:.4f} | "
                f"{d['error']['p95_rel']:+.1%} | {d['accept']['p95']} |",
                f"| CPU-seconds | {d['real']['cpu_s']:.1f} | {d['sim']['cpu_s_mean']:.1f} | "
                f"{d['error']['compute_s_rel']:+.1%} | {d['accept']['compute_s']} |",
                f"| p50 latency (s) | {d['real']['p50_s']:.4f} | {d['sim']['p50_s_mean']:.4f} | | |",
                f"| p99 latency (s) | {d['real']['p99_s']:.4f} | {d['sim']['p99_s_mean']:.4f} | | |", "",
                f"Overall: **{'PASS' if d['accept']['overall'] else 'FAIL'}**. Queries: {d['n_queries']} "
                f"arrivals, {d['n_completed_real']} completed in the real replay.", ""]

    rs = j("redset_sweep")
    if rs:
        t = rs["meta"]["settings"]["trace"]
        df = pd.DataFrame(rs["data"]["summary_mean"])
        df["policy"] = pd.Categorical(df.policy, POL)
        out += ["## Table 4 – Redset replay (one instance-day, means over 10 seeds)", "",
                f"Source: results/redset_sweep.parquet, results/redset_sweep.json, results/redset_trace.json. "
                f"Instance {t['instance_id']}, day {t['day']}, {t['n_queries']} queries, hourly CV "
                f"{t['hourly_cv']:.2f}; S-tuned τ = {rs['data']['tuned_tau_s']:.0f} s.", "",
                md_table(df.sort_values("policy")), ""]
    else:
        out += ["## Table 4 – Redset replay", "", "Not run (see cuts).", ""]

    st = j("stats")
    if st:
        out += ["## Table 5 – Statistics", "", f"Source: results/stats.csv ({st['data']['rows']} rows): "
                "mean ± std, bootstrap 95 % CI (10,000 resamples), Wilcoxon signed-rank vs P-peak paired by "
                "seed, per metric, policy and cell.", ""]


    # ---- Tier 6: contention fix + revalidation (v1 tables above are kept as-is) ----
    cc = j("calib_contention")
    if cc:
        out += ["## Table 6 – Concurrency calibration and contention fit (Tier 6B)", "",
                "Source: results/calib_contention.json. Closed loop, 8-query mix, 120 s per level, "
                "cold restart once per size. Model latency = base_q × max(1, a·n/c), fitted only on this file.", "",
                "| size | n | completed | errors | CPU-s | wall s | mean ratio | mean pred | mean resid |",
                "|---|---|---|---|---|---|---|---|---|"]
        for size, d in cc["data"].items():
            f = d["fit"]
            for L in d["levels"]:
                r = f["residuals_by_n"][str(L["n"])] if str(L["n"]) in f["residuals_by_n"] else f["residuals_by_n"][L["n"]]
                out.append(f"| {size} | {L['n']} | {L['completed']} | {len(L['errors'])} | {L['cpu_s']:.1f} | "
                           f"{L['wall_s']:.0f} | {r['mean_ratio']:.3f} | {r['mean_pred']:.3f} | {r['mean_resid']:+.3f} |")
            out += ["", f"{size}: a = {f['a']:.3f}, R² = {f['r2']:.3f}, cpu_per_base = {f['cpu_per_base']:.3f} "
                    f"(CPU-seconds per second of uncontended service).", ""]

    v2 = j("validation_v2")
    if v2:
        d, st_ = v2["data"], v2["meta"]["settings"]
        rows = ["| sim | p95 real | p95 sim | p95 error | CPU-s real | CPU-s sim | CPU-s error | pass |",
                "|---|---|---|---|---|---|---|---|"]
        for ver, r in d["sim"].items():
            rows.append(f"| {ver} | {d['real']['p95_s']:.4f} | {r['p95_s_mean']:.4f} | {r['error']['p95_rel']:+.1%} | "
                        f"{d['real']['cpu_s']:.1f} | {r['cpu_s_mean']:.1f} | {r['error']['compute_s_rel']:+.1%} | "
                        f"{'PASS' if r['accept']['overall'] else 'FAIL'} |")
        out += ["## Table 7 – Validation v2 (new trace, sim v1 and sim v2)", "",
                f"Source: results/validation_v2.json. Trace seed {st_['trace_seed']} (v1 used {st_['v1_trace_seed']}); "
                "same workload shape and frozen bands (|p95 error| ≤ 25 %, |CPU-s error| ≤ 20 %). "
                f"Real replay: {d['n_queries']} arrivals, {d['n_completed_real']} completed, {d['n_errors']} errors "
                f"{d['errors_by_class']}, {d['n_unaccounted']} unaccounted.", ""] + rows + [""]

    oc = j("redset_overload_check")
    if oc:
        d = oc["data"]
        m = d["minute_resolution"]
        out += ["## Table 8 – Redset P-mean overload check", "",
                "Source: results/redset_overload_check.json.", "",
                "| quantity | value |", "|---|---|",
                f"| P-mean size (vCPU) / servers | {d['p_mean_size_vcpu']} / {d['servers_k']} |",
                f"| capacity (q/s) | {d['capacity_qps']:.2f} |",
                f"| ρ day mean | {d['rho_day_mean']:.3f} |",
                f"| ρ peak hour (hour {d['peak_hour']}) | {d['rho_peak_hour']:.3f} |",
                f"| ρ max minute | {m['rho_max_minute']:.3f} |",
                f"| minutes with ρ > 1 | {m['minutes_with_rho_gt_1']} |",
                f"| max fluid backlog (queries) / drain (s) | {m['fluid_backlog_max_queries_minute_res']} / {m['fluid_backlog_max_drain_s']} |",
                f"| queue unbounded during overload minutes | {d['queue_unbounded_during_overload_minutes']} |",
                f"| sim v1 P-mean p95 (s) | {d['sim_v1_p_mean']['p95_s_mean']:.1f} |", ""]

    sw2 = j("sweep_v2")
    if sw2:
        a1 = pd.read_parquet(R / "sweep.parquet")
        a1 = a1[~a1.aux].groupby(["intensity", "gap", "policy"])[["p95_s", "cost_per_1k_usd"]].mean()
        a2 = pd.read_parquet(R / "sweep_v2.parquet")
        a2 = a2[~a2.aux & (a2.split == "eval")].groupby(["intensity", "gap", "policy"])[
            ["p95_s", "cost_per_1k_usd", "meets_p95"]].mean()
        t = a1.join(a2, lsuffix="_v1", rsuffix="_v2").round(4).reset_index()
        t["policy"] = pd.Categorical(t.policy, POL)
        t = t.sort_values(["intensity", "gap", "policy"])
        out += ["## Table 9 – Synthetic sweep, sim v1 vs sim v2", "",
                "Source: results/sweep.parquet (v1, seeds 0–9, S-tuned in-sample) and results/sweep_v2.parquet "
                "(v2, S-tuned τ chosen on seeds 0–9, all policies scored on held-out seeds 10–19). "
                "S-tuned τ (v2): " + ", ".join(f"{k} {v['tau_s']:.0f}s" for k, v in sw2["data"]["tuned_tau"].items())
                + ".", "", md_table(t), ""]
    rs2 = j("redset_sweep_v2")
    if rs2:
        df = pd.DataFrame(rs2["data"]["summary_mean"])
        df["policy"] = pd.Categorical(df.policy, POL)
        out += ["## Table 10 – Redset replay, sim v2 (held-out seeds 10–19)", "",
                f"Source: results/redset_sweep_v2.parquet, results/redset_sweep_v2.json; S-tuned τ = "
                f"{rs2['data']['tuned_tau_s']:.0f} s chosen on seeds 0–9.", "", md_table(df.sort_values("policy")), ""]
    head = ("**Headline version:** sim v2 (Tables 9–10) because it passed validation v2; v1 tables are kept for comparison."
            if v2 and d_pass(v2) and sw2 else
            "**Headline version:** no simulator version passed validation; Tables 2 and 4 (sim v1) are reported "
            "as-is and are NOT validated. Sweep latencies under load are optimistic (see Tables 3 and 7).")
    out += ["## Which version the headline numbers use", "", head, ""]

    fg = j("figures")
    if fg:
        src = {"calibration_docker": "results/calib_docker.json",
               "latency_cdf": "results/sweep_latency_seed0.parquet",
               "cost_vs_p95": "results/sweep.parquet", "cold_starts_by_gap": "results/sweep.parquet",
               "validation_sim_vs_real": "results/validation.json (+ simulator seed 0 on the same trace)",
               "redset_cost_vs_p95": "results/redset_sweep.parquet",
               "contention_fit": "results/calib_contention.json",
               "validation_v2_sim_vs_real": "results/validation_v2.json (+ sim v1/v2 seed 0 on the same trace)",
               "cost_vs_p95_v2": "results/sweep_v2.parquet (held-out seeds)"}
        out += ["## Figures", "", "| figure | source |", "|---|---|"]
        for f in fg["data"]["files"]:
            if f.endswith(".pdf"):
                stem = Path(f).stem
                out.append(f"| {f} (+ .png) | {src.get(stem, '?')} |")
        if fg["data"]["failed"]:
            out.append(f"\nFailed figures: {fg['data']['failed']}")
        out.append("")

    out += ["## Result files", ""]
    for p in sorted(R.glob("*")):
        if p.is_file() and p.name != ".gitkeep":
            out.append(f"- results/{p.name}")
    out += ["- results/hp_bootstrap/ (HP, not used)", ""]

    dec = (common.REPO_ROOT / "DECISIONS.md").read_text(encoding="utf-8")
    tk = dec.split("### Dell G15 takeover", 1)
    out += ["## Deviations and cuts (2026-10-16, from DECISIONS.md)", ""]
    if len(tk) == 2:
        out += [l for l in tk[1].splitlines()[1:] if l.startswith("- ")]
    out += ["", (common.REPO_ROOT / "configs" / "threats.md").read_text(encoding="utf-8")]
    (common.REPO_ROOT / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote RESULTS.md", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
