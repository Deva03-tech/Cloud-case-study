"""Generate RESULTS.md: every number is read from results/ files (no retyping).

Sections: tables (calibration, sweep, validation, Redset, stats pointer), figures, result
file inventory, deviations and cuts (from DECISIONS.md, Dell takeover section), threats.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src import common  # noqa: E402

R = common.RESULTS_DIR
POL = ["P-peak", "P-mean", "P-sched", "S-default", "S-tuned", "S-floor", "S-prewarm"]


def j(name: str) -> dict | None:
    p = R / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in r.tolist()) + " |")
    return "\n".join(lines)


def main() -> int:
    out = ["# RESULTS", "",
           "Generated by `scripts/make_results_md.py` from the files in `results/`; every number "
           "below is read from the named file. Host: Dell G15 (results/machine_dell.json). "
           "HP measurements in results/hp_bootstrap/ are not used.", ""]
    m = j("machine_dell")
    if m:
        d = m["data"]
        out += ["## Machine", "", f"{d['machine']}, {d['cpu']} ({d['cores']} cores / {d['threads']} threads), "
                f"{d['ram_gb']} GB RAM, Windows build {d['windows_build']}. Source: results/machine_dell.json.", ""]

    c = j("calib_docker")
    if c:
        rows = []
        for q in sorted(c["data"]["s1"]["queries"]):
            r = {"query": q}
            for s in ("s1", "s2", "s4"):
                qq = c["data"][s]["queries"][q]
                r[f"{s} warm med"] = qq["warm"]["median_s"]
                r[f"{s} warm p95"] = qq["warm"]["p95_s"]
                r[f"{s} cold med"] = qq["cold_first_query"]["median_s"]
            rows.append(r)
        sent = ", ".join(f"{s}: {c['data'][s]['sentinel_q6_start_s']}→{c['data'][s]['sentinel_q6_end_s']} s"
                         for s in ("s1", "s2", "s4"))
        out += ["## Table 1 – Docker calibration (seconds)", "",
                "Source: results/calib_docker.json. s1/s2/s4 = 1/2/4 vCPU with 2/3/5 GB; 3 cold runs, "
                "1 warm-up + 5 warm reps per query and size.", "", md_table(pd.DataFrame(rows)), "",
                f"Q6 sentinel start→end: {sent}.", ""]

    sw = j("sweep")
    if sw:
        df = pd.read_parquet(R / "sweep.parquet")
        df = df[~df.aux]
        g = df.groupby(["intensity", "gap", "policy"]).agg(
            p95=("p95_s", "mean"), p99=("p99_s", "mean"), cost1k=("cost_per_1k_usd", "mean"),
            vcpu_s=("compute_vcpu_s", "mean"), cold=("cold_starts", "mean"),
            meets_p95=("meets_p95", "mean")).round(4).reset_index()
        g["policy"] = pd.Categorical(g.policy, POL)
        g = g.sort_values(["intensity", "gap", "policy"])
        d = sw["data"]
        out += ["## Table 2 – Synthetic burst sweep (means over 10 seeds)", "",
                f"Source: results/sweep.parquet, results/sweep.json. {d['runs_total']} runs; "
                f"p95 target {d['p95_target_s']} s, p99 target {d['p99_target_s']} s; "
                "meets_p95 = share of seeds meeting the p95 target. Serverless priced as Aurora "
                "Serverless v2, provisioned as RDS (configs/prices.yaml).", "", md_table(g), "",
                "S-tuned timeout per cell: " + ", ".join(
                    f"{k} τ={v['tau_s']:.0f}s{'' if v['meets_target'] else ' (no τ met target)'}"
                    for k, v in d["tuned_tau"].items()) + ".", ""]

    v = j("validation")
    if v:
        d = v["data"]
        out += ["## Table 3 – Validation (simulator vs real Docker s2 replay, 10 min)", "",
                "Source: results/validation.json. Acceptance frozen before the run: |p95 error| ≤ 25 %, "
                "|compute-seconds error| ≤ 20 %.", "",
                "| metric | real | sim (mean of 10 seeds) | error | pass |", "|---|---|---|---|---|",
                f"| p95 latency (s) | {d['real']['p95_s']:.4f} | {d['sim']['p95_s_mean']:.4f} | "
                f"{d['error']['p95_rel']:+.1%} | {d['accept']['p95']} |",
                f"| CPU-seconds | {d['real']['cpu_s']:.1f} | {d['sim']['cpu_s_mean']:.1f} | "
                f"{d['error']['compute_s_rel']:+.1%} | {d['accept']['compute_s']} |",
                f"| p50 latency (s) | {d['real']['p50_s']:.4f} | {d['sim']['p50_s_mean']:.4f} | | |",
                f"| p99 latency (s) | {d['real']['p99_s']:.4f} | {d['sim']['p99_s_mean']:.4f} | | |", "",
                f"Overall: **{'PASS' if d['accept']['overall'] else 'FAIL'}**. Queries: {d['n_queries']} "
                f"arrivals, {d['n_completed_real']} completed in the real replay.", ""]

    rs = j("redset_sweep")
    if rs:
        t = rs["meta"]["settings"]["trace"]
        df = pd.DataFrame(rs["data"]["summary_mean"])
        df["policy"] = pd.Categorical(df.policy, POL)
        out += ["## Table 4 – Redset replay (one instance-day, means over 10 seeds)", "",
                f"Source: results/redset_sweep.parquet, results/redset_sweep.json, results/redset_trace.json. "
                f"Instance {t['instance_id']}, day {t['day']}, {t['n_queries']} queries, hourly CV "
                f"{t['hourly_cv']:.2f}; S-tuned τ = {rs['data']['tuned_tau_s']:.0f} s.", "",
                md_table(df.sort_values("policy")), ""]
    else:
        out += ["## Table 4 – Redset replay", "", "Not run (see cuts).", ""]

    st = j("stats")
    if st:
        out += ["## Table 5 – Statistics", "", f"Source: results/stats.csv ({st['data']['rows']} rows): "
                "mean ± std, bootstrap 95 % CI (10,000 resamples), Wilcoxon signed-rank vs P-peak paired by "
                "seed, per metric, policy and cell.", ""]

    fg = j("figures")
    if fg:
        src = {"calibration_docker": "results/calib_docker.json",
               "latency_cdf": "results/sweep_latency_seed0.parquet",
               "cost_vs_p95": "results/sweep.parquet", "cold_starts_by_gap": "results/sweep.parquet",
               "validation_sim_vs_real": "results/validation.json (+ simulator seed 0 on the same trace)",
               "redset_cost_vs_p95": "results/redset_sweep.parquet"}
        out += ["## Figures", "", "| figure | source |", "|---|---|"]
        for f in fg["data"]["files"]:
            if f.endswith(".pdf"):
                stem = Path(f).stem
                out.append(f"| {f} (+ .png) | {src.get(stem, '?')} |")
        if fg["data"]["failed"]:
            out.append(f"\nFailed figures: {fg['data']['failed']}")
        out.append("")

    out += ["## Result files", ""]
    for p in sorted(R.glob("*")):
        if p.is_file() and p.name != ".gitkeep":
            out.append(f"- results/{p.name}")
    out += ["- results/hp_bootstrap/ (HP, not used)", ""]

    dec = (common.REPO_ROOT / "DECISIONS.md").read_text(encoding="utf-8")
    tk = dec.split("### Dell G15 takeover", 1)
    out += ["## Deviations and cuts (2026-10-16, from DECISIONS.md)", ""]
    if len(tk) == 2:
        out += [l for l in tk[1].splitlines()[1:] if l.startswith("- ")]
    out += ["", (common.REPO_ROOT / "configs" / "threats.md").read_text(encoding="utf-8")]
    (common.REPO_ROOT / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote RESULTS.md", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
